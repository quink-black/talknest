"""Build the device avatar expression frames from the community whale-girl art.

Source: web/whale_front.webp (RGBA character with transparent background).
Output:
  firmware/components/ui_avatar/assets/avatar_frames.bin
      Four RGB565 frames back to back (eyes open/closed x mouth closed/open).
  firmware/components/ui_avatar/include/avatar_frames.h
      Declares the embedded symbol and frame geometry.

The device has no image decoder, so frames are baked to raw RGB565 bytes and
embedded with CMake EMBED_FILES. The transparent background is composited
onto the screen's dark background, letting us use plain RGB565 (2 bytes/px).

Run: ./venv-tts/bin/python scripts/gen_avatar_frames.py
     ./venv-tts/bin/python scripts/gen_avatar_frames.py --preview /tmp/avatar.png
"""

import argparse
import sys
from pathlib import Path

import numpy as np
from PIL import Image, ImageDraw

REPO = Path(__file__).resolve().parent.parent
SOURCE = REPO / "web" / "whale_front.webp"
ASSETS = REPO / "firmware" / "components" / "ui_avatar" / "assets"
INCLUDE = REPO / "firmware" / "components" / "ui_avatar" / "include"
BINARY = ASSETS / "avatar_frames.bin"
HEADER = INCLUDE / "avatar_frames.h"

# Crop of the source that fills the device screen with the face as the focus.
# 200x205 keeps the dirty rect at 41000 px, one partial-refresh flush per frame.
CROP = (59, 20, 259, 225)
SIZE = (200, 205)
BG = (16, 20, 28)  # matches ui_status.cpp's screen background 0x10141C

# Feature coordinates in source pixels (calibrated on the gridded face crop).
EYES = [(98, 138, 140, 180), (180, 138, 222, 180)]
EYE_ARCS = [(101, 150, 137, 166), (183, 150, 219, 166)]
MOUTH = (149, 183, 169, 200)

# Frame order in the binary, mirrored by the C enum.
FRAME_NAMES = ["idle", "talk", "blink", "blink_talk"]


def skin_color(rgb):
    """Average a clean patch of cheek to cover the open eyes with."""
    patch = rgb[188:198, 140:180].reshape(-1, 3)
    return tuple(int(v) for v in patch.mean(axis=0))


def paint_eyes_closed(img, skin):
    d = ImageDraw.Draw(img)
    for box in EYES:
        d.ellipse(box, fill=skin)
    for box in EYE_ARCS:
        d.arc(box, start=195, end=345, fill=(46, 58, 92), width=4)


def paint_mouth_open(img):
    d = ImageDraw.Draw(img)
    d.ellipse(MOUTH, fill=(122, 56, 68), outline=(90, 40, 52), width=2)
    d.ellipse((154, 192, 164, 199), fill=(214, 116, 124))


def rgb565_bytes(img):
    a = np.asarray(img.convert("RGB"), dtype=np.uint16)
    r, g, b = a[:, :, 0], a[:, :, 1], a[:, :, 2]
    v = ((r >> 3) << 11) | ((g >> 2) << 5) | (b >> 3)
    return v.astype("<u2").tobytes()  # LVGL RGB565 is little-endian on ESP32


def build():
    src = Image.open(SOURCE).convert("RGBA")
    base = Image.new("RGB", src.size, BG)
    base.paste(src, mask=src.getchannel("A"))
    skin = skin_color(np.asarray(base))
    print(f"skin {skin}, source {src.size}")
    frames = {}
    for eyes_closed in (False, True):
        for mouth_open in (False, True):
            img = base.copy()
            if eyes_closed:
                paint_eyes_closed(img, skin)
            if mouth_open:
                paint_mouth_open(img)
            key = ("blink" if eyes_closed else "idle") if not mouth_open else \
                  ("blink_talk" if eyes_closed else "talk")
            frames[key] = img.crop(CROP)
    return frames


def write_binary(frames):
    w, h = SIZE
    size = w * h * 2
    ASSETS.mkdir(parents=True, exist_ok=True)
    with BINARY.open("wb") as out:
        for name in FRAME_NAMES:
            raw = rgb565_bytes(frames[name])
            assert len(raw) == size, (name, len(raw), size)
            out.write(raw)
    print(f"wrote {BINARY} ({BINARY.stat().st_size} bytes)")


def write_header():
    w, h = SIZE
    HEADER.parent.mkdir(parents=True, exist_ok=True)
    HEADER.write_text("\n".join([
        "/* Generated by scripts/gen_avatar_frames.py -- do not edit by hand.",
        " * Four expression frames for the dialogue-driven avatar.",
        " * Source: web/whale_front.webp (community whale-girl fan art).",
        " * Format: LV_COLOR_FORMAT_RGB565, little-endian, opaque.",
        " * Frame order matches avatar_frames.bin and the enum below. */",
        "#pragma once",
        "",
        "#include <stdint.h>",
        "",
        f"#define AVATAR_FRAME_W {w}",
        f"#define AVATAR_FRAME_H {h}",
        "#define AVATAR_FRAME_BYTES (AVATAR_FRAME_W * AVATAR_FRAME_H * 2)",
        "#define AVATAR_FRAME_COUNT 4",
        "",
        "enum avatar_frame_t {",
        "    AVATAR_FRAME_IDLE = 0,   /* eyes open, mouth closed */",
        "    AVATAR_FRAME_TALK,       /* eyes open, mouth open  */",
        "    AVATAR_FRAME_BLINK,      /* eyes closed, mouth closed */",
        "    AVATAR_FRAME_BLINK_TALK, /* eyes closed, mouth open */",
        "};",
        "",
        "",
    ]) + "\n", encoding="utf-8")
    print(f"wrote {HEADER}")


def preview(frames, path):
    sheet = Image.new("RGB", (SIZE[0] * 4, SIZE[1]), BG)
    for i, name in enumerate(FRAME_NAMES):
        sheet.paste(frames[name], (i * SIZE[0], 0))
    sheet.save(path)
    print(f"preview {path}")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--preview")
    args = ap.parse_args()
    if not SOURCE.exists():
        sys.exit(f"missing {SOURCE}")
    frames = build()
    if args.preview:
        preview(frames, args.preview)
    write_binary(frames)
    write_header()


if __name__ == "__main__":
    main()
